#pragma once

// ============================================================================
//  include/notify_title.h —— 内部头：通知标题模板的占位符展开
//
//  **不是插件对外接口**：只有本插件的通知后端（Windows 气泡 / Linux libnotify）
//  包含它。标题模板来自配置项 `title`（STRING），空串表示"用默认多语言标题"。
//
//  为什么单独一个模块：两个平台后端都要把同一份模板展开成最终标题，展开规则必须
//  只有一份；放进 NotifyConfig 会让"配置存储"和"文本渲染"混在一起（STYLE §6.6）。
//
//  规则刻意保持朴素——只做一次从左到右的字符串替换，不解析嵌套、不递归展开、
//  不引入模板引擎：
//    · {path}   → 图片绝对路径（失败通知没有路径，替换成空串）
//    · {width}  → 图片宽度（像素；未知时替换成空串）
//    · {height} → 图片高度（像素；未知时替换成空串）
//    · 其它 {} 原样保留（用户写错占位符时能看到自己的原文，便于对照工具提示）
// ============================================================================

#include <string>

namespace notify {

/**
 * @brief 把标题模板里的占位符替换成实际值。
 *
 * 展开是"单趟扫描"：替换进去的值不会再被当成模板重新解析（例如路径里恰好含有
 * `{path}` 时不会死循环）。模板为空时返回空串，由调用方回落到默认多语言标题。
 *
 * @param[in] titleTemplate 配置里的标题模板（UTF-8）；空串返回空串。
 * @param[in] path          图片绝对路径（UTF-8）；没有路径时传空串。
 * @param[in] width         图片宽度（像素）；<= 0 表示未知，替换成空串。
 * @param[in] height        图片高度（像素）；<= 0 表示未知，替换成空串。
 * @return 展开后的标题（UTF-8）；模板里没有占位符时原样返回模板。
 */
std::string expandTitle(const std::string& titleTemplate, const std::string& path, int width,
                        int height);

}  // namespace notify
